import { writeFile } from 'node:fs/promises';
import { z } from 'zod';
import { fetchAllCircuits } from '@/clients/jolpica.js';
import type { JolpicaCircuit } from '@/types/f1.js';
import type { TrackOutline } from '@/types/track.js';
import { centroid, haversineKm, normalize, projectToMetres, rotateToLandscape, simplifyToRange } from '@/utils/geo.js';

const SOURCE_COMMIT = '8094e957b8d6aa8b9f4510c93968556cccd30e02';
const SOURCE_URL = `https://raw.githubusercontent.com/bacinger/f1-circuits/${SOURCE_COMMIT}/f1-circuits.geojson`;
const OUTPUT = new URL('../data/track-outlines.generated.ts', import.meta.url);

const MAX_MATCH_KM = 3;
const AMBIGUOUS_KM = 3;
const MIN_POINTS = 60;
const MAX_POINTS = 100;
const SIZE = 1000;

// Two Jolpica circuits sit within AMBIGUOUS_KM of these tracks, so nearest-wins would be luck.
const OVERRIDES: Record<string, string> = {
  'us-2023': 'vegas',
  'at-1969': 'red_bull_ring',
};

const GeoJsonSchema = z.object({
  type: z.literal('FeatureCollection'),
  features: z.array(
    z.object({
      properties: z.object({ id: z.string(), Name: z.string(), length: z.number().optional() }),
      geometry: z.object({
        type: z.literal('LineString'),
        coordinates: z.array(z.tuple([z.number(), z.number()])).min(3),
      }),
    }),
  ),
});

async function loadTracks() {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`bacinger/f1-circuits ${res.status}`);
  return GeoJsonSchema.parse(await res.json()).features;
}

async function loadCircuits(): Promise<JolpicaCircuit[]> {
  const data = (await fetchAllCircuits()).MRData;
  if (Number(data.total) > Number(data.limit)) throw new Error(`Jolpica has ${data.total} circuits, raise the limit`);
  return data.CircuitTable.Circuits;
}

function matchCircuit(trackId: string, lat: number, lon: number, circuits: JolpicaCircuit[]): JolpicaCircuit | null {
  const ranked = circuits
    .map((circuit) => ({
      circuit,
      km: haversineKm(lat, lon, Number(circuit.Location.lat), Number(circuit.Location.long)),
    }))
    .sort((a, b) => a.km - b.km);

  const override = OVERRIDES[trackId];
  if (override) {
    const match = ranked.find((r) => r.circuit.circuitId === override);
    if (!match || match.km > MAX_MATCH_KM) throw new Error(`Override ${trackId} -> ${override} is not nearby`);
    return match.circuit;
  }

  const [first, second] = ranked;
  if (!first || first.km > MAX_MATCH_KM) return null;
  if (second && second.km < AMBIGUOUS_KM) {
    throw new Error(
      `${trackId} is ambiguous: ${first.circuit.circuitId} (${first.km.toFixed(2)} km) or ` +
        `${second.circuit.circuitId} (${second.km.toFixed(2)} km). Add it to OVERRIDES.`,
    );
  }
  return first.circuit;
}

async function main() {
  const [tracks, circuits] = await Promise.all([loadTracks(), loadCircuits()]);
  const outlines = new Map<string, TrackOutline>();
  const unmatched: string[] = [];

  for (const { properties, geometry } of tracks) {
    const { lat, lon } = centroid(geometry.coordinates);
    const circuit = matchCircuit(properties.id, lat, lon, circuits);
    if (!circuit) {
      unmatched.push(`${properties.id} (${properties.Name})`);
      continue;
    }

    const existing = outlines.get(circuit.circuitId);
    if (existing) throw new Error(`${properties.id} and ${existing.sourceId} both match ${circuit.circuitId}`);

    const simplified = simplifyToRange(projectToMetres(geometry.coordinates), MIN_POINTS, MAX_POINTS);
    const { points, rotation } = rotateToLandscape(simplified);
    outlines.set(circuit.circuitId, {
      circuitId: circuit.circuitId,
      name: circuit.circuitName,
      sourceId: properties.id,
      lengthM: properties.length ?? null,
      rotation,
      ...normalize(points, SIZE),
    });
  }

  const entries = [...outlines.values()]
    .sort((a, b) => a.circuitId.localeCompare(b.circuitId))
    .map((outline) => `  [${JSON.stringify(outline.circuitId)}, ${JSON.stringify(outline)}],`);

  const source =
    `// Generated by src/scripts/build-tracks.ts from bacinger/f1-circuits@${SOURCE_COMMIT.slice(0, 7)} (MIT). Do not edit.\n` +
    `import type { TrackOutline } from '@/types/track.js';\n\n` +
    `export const TRACK_OUTLINES = new Map<string, TrackOutline>([\n${entries.join('\n')}\n]);\n`;

  await writeFile(OUTPUT, source);

  const counts = [...outlines.values()].map((o) => o.points.length);
  console.log(`Wrote ${outlines.size} outlines, ${Math.min(...counts)}–${Math.max(...counts)} points each`);
  if (unmatched.length > 0) console.log(`No Jolpica circuit within ${MAX_MATCH_KM} km: ${unmatched.join(', ')}`);
}

await main();
